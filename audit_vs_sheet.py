# DB에서 전체 출고 조회
db_rows = conn.execute("""
    SELECT o.date, c.name, p.name, o.quantity, o.supply_amount, o.vat_amount, o.total_amount
    FROM stock_out o
    JOIN clients c ON o.client_id=c.id
    JOIN products p ON o.product_id=p.id
    WHERE o.type='출고'
    ORDER BY o.date, o.id
""").fetchall()

print("=" * 80)
print("스프레드시트 vs DB 전체 비교")
print("=" * 80)

errors = []
matched = 0

for s_date, s_client, s_prod, s_qty, s_unit_price in sheet_out:
    s_supply = s_unit_price * s_qty

    # DB에서 일치하는 행 찾기
    match = None
    for r in db_rows:
        if r[0] == s_date and r[1] == s_client and r[2] == s_prod and r[3] == s_qty:
            match = r
            break

    if match is None:
        errors.append(f"[누락] {s_date} {s_client} {s_prod} ×{s_qty} = ₩{s_supply:,}")
        continue

    db_supply = match[4]
    db_vat    = match[5]
    db_total  = match[6]

    if db_supply != s_supply:
        errors.append(
            f"[금액오류] {s_date} {s_client} {s_prod} ×{s_qty}\n"
            f"  시트: 공급가={s_supply:,}  DB: 공급가={db_supply:,}  차이={db_supply-s_supply:+,}"
        )
    else:
        matched += 1

print(f"\n총 항목: {len(sheet_out)}개")
print(f"일치:    {matched}개")
print(f"오류:    {len(errors)}개")

if errors:
    print("\n[발견된 오류]")
