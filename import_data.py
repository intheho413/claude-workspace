for so in stock_out_data:
    dt, client, prod, qty, unit_supply = so
    pid = prod_map[prod]
    cid = client_map.get(client)
    if not cid:
        warnings.append(f"거래처 없음: {client}")
        continue

    disc_rate = client_disc_map.get(client, 0.0)

    # FIFO: 재고 배치 조회 (날짜 순)
    batches = conn.execute("""
        SELECT id, remaining_qty, purchase_price FROM stock_in
        WHERE product_id=? AND remaining_qty>0 AND date<=?
        ORDER BY date ASC
    """, (pid, dt)).fetchall()

    total_cost = 0
    remaining  = qty
    updates    = []
    last_price = 0

    for bid, brq, bprice in batches:
        if remaining <= 0:
            break
        use = min(remaining, brq)
        total_cost += use * bprice
        updates.append((use, bid))
        remaining -= use
        last_price = bprice

    if remaining > 0:
        warnings.append(f"재고부족: {prod} {dt} ({remaining}개 부족) → 마지막 단가로 처리")
        total_cost += remaining * last_price

    # 금액 계산 (unit_supply = 단위 공급가, VAT 제외)
    supply_amount = unit_supply * qty
    vat_amount    = round(supply_amount * 0.1)
    total_amount  = supply_amount + vat_amount
    fifo_pp       = round(total_cost / qty) if qty > 0 else 0
    margin_amount = supply_amount - total_cost
    margin_rate   = (margin_amount / supply_amount * 100) if supply_amount > 0 else 0

    conn.execute("""
        INSERT INTO stock_out
            (date, client_id, product_id, type, quantity, discount_rate,
             supply_amount, vat_amount, total_amount,
             fifo_purchase_price, margin_amount, margin_rate)
        VALUES (?,?,?,?,?,?,?,?,?,?,?,?)
    """, (dt, cid, pid, "출고", qty, disc_rate,
          supply_amount, vat_amount, total_amount,
          fifo_pp, margin_amount, margin_rate))

    for use_qty, bid in updates:
        conn.execute("UPDATE stock_in SET remaining_qty=remaining_qty-? WHERE id=?", (use_qty, bid))

    out_count += 1

